import os
import sys
import json
import time

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from backend.app.pipeline import execute_rag_pipeline
from dotenv import load_dotenv

load_dotenv()

def generate_comparison(dataset_path="evaluation/test_dataset.json", output_path="evaluation/qa_comparison.md"):
    if not os.path.exists(dataset_path):
        print("Dataset not found!")
        return

    with open(dataset_path, "r", encoding="utf-8") as f:
        cases = json.load(f)

    # We only care about the first 14
    cases = cases[:14]
    
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("# RAG Generation vs Expected Answers\n\n")
        f.write("This document compares the expected answers from the dataset against the actual answers generated by the local Mistral model via the RAG pipeline.\n\n")

    print(f"Generating answers for {len(cases)} queries...")
    for idx, case in enumerate(cases):
        print(f"[{idx+1}/{len(cases)}] Querying: {case['query']}")
        try:
            rag_output = execute_rag_pipeline(case["file_id"], case["query"], top_p=3)
            actual_answer = rag_output["actual_output"]
            
            # Append to markdown file incrementally
            with open(output_path, "a", encoding="utf-8") as f:
                f.write(f"## Question {idx+1}\n")
                f.write(f"**Query:** {case['query']}\n\n")
                f.write("### Expected Answer\n")
                f.write(f"> {case['expected_output']}\n\n")
                f.write("### RAG Generated Answer (Mistral)\n")
                f.write(f"{actual_answer}\n")
                f.write("---\n\n")
                
        except Exception as e:
            print(f"Error on query {idx+1}: {e}")
            with open(output_path, "a", encoding="utf-8") as f:
                f.write(f"## Question {idx+1}\n")
                f.write(f"**Query:** {case['query']}\n\n")
                f.write(f"**Error generating answer:** {e}\n\n")
                f.write("---\n\n")
                
    print(f"Finished! Saved comparison to {output_path}")

if __name__ == "__main__":
    generate_comparison()
